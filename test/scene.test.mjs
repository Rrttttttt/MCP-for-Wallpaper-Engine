import { test } from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { Projects, validate } from '../dist/projects.js';
import { readTree } from '../dist/files.js';

test('Scene template preserves source and compiled assets, validates image dependencies and records template origin',async t=>{
  const workspace=await fs.mkdtemp(path.join(os.tmpdir(),'we-scene-'));
  t.after(()=>fs.rm(workspace,{recursive:true,force:true}));
  const projects=new Projects({workspace,projectRoots:[],timeoutMs:1000});
  await projects.init();
  const created=await projects.create('scene','Scene',{speed:0.5,amplitude:120},undefined,'scene-orbit');
  assert.equal(created.manifest.type,'scene');
  assert.equal(created.manifest.general.properties.amplitude.value,120);
  assert.equal(created.validation.valid,true);
  assert.deepEqual(created.validation.sceneDependencies.map(d=>d.status),['local','local','local']);
  assert.equal(JSON.parse(await fs.readFile(path.join(workspace,'origins','scene.json'))).templateId,'scene-orbit');
  const files=await readTree(created.path);
  assert.ok(files.has('materials/mcp_orb.png'));
  assert.equal(files.get('materials/mcp_orb.tex').toString('ascii',0,8),'TEXV0005');
  files.delete('materials/mcp_orb.tex');
  assert.match(validate(files).errors.join(),/requires compilation/);
  files.set('materials/mcp_orb.tex',Buffer.from('not a TEX'));
  assert.match(validate(files).errors.join(),/Invalid compiled texture/);
  const original=await readTree(fileURLToPath(new URL('../templates/scene-orbit/',import.meta.url)));
  const scene=JSON.parse(original.get('scene.json'));
  scene.objects.push({...scene.objects[0],id:2});
  original.set('scene.json',Buffer.from(JSON.stringify(scene)));
  assert.equal(validate(original).valid,true);
  assert.equal(validate(original).sceneDependencies.length,3);
  scene.objects.pop();
  scene.objects[0].image='../outside.json';
  original.set('scene.json',Buffer.from(JSON.stringify(scene)));
  assert.match(validate(original).errors.join(),/Unsafe Scene/);
  scene.objects[0].image='models/util/solidlayer.json';
  original.set('scene.json',Buffer.from(JSON.stringify(scene)));
  const shared=validate(original);
  assert.equal(shared.valid,true);
  assert.equal(shared.sceneDependencies[0].status,'unresolved');
  await assert.rejects(projects.create('bad','Bad',{},undefined,'../escape'),{code:'INVALID_TEMPLATE'});
});

test('SceneScript reads current raw host properties, pauses and normalizes motion across frame rates without drift',async()=>{
  const scene=JSON.parse(await fs.readFile(new URL('../templates/scene-orbit/scene.json',import.meta.url),'utf8'));
  const script=scene.objects[0].origin.script;
  const setup=()=>{
    const engine={frametime:1/60,userProperties:{speed:0.3,amplitude:240}};
    const context=vm.createContext({engine,Math});
    vm.runInContext(script.replaceAll('export function','function')+'\nglobalThis.hooks={init,update};',context);
    const value={x:640,y:360,z:0,copy(){return {x:this.x,y:this.y,z:this.z}}};
    const hooks=context.hooks; hooks.init(value);
    return {engine,hooks,value};
  };
  const a=setup(),b=setup();
  a.engine.userProperties.speed=0.5;
  b.engine.userProperties.speed=0.5;
  for(let i=0;i<30;i++) a.hooks.update(a.value);
  b.engine.frametime=1/30;
  for(let i=0;i<15;i++) b.hooks.update(b.value);
  assert.ok(Math.abs(a.value.x-b.value.x)<1e-6);
  assert.ok(Math.abs(a.value.x-880)<1e-6);
  a.engine.frametime=0; const frozen=a.value.x;
  assert.equal(a.hooks.update(a.value).x,frozen);
  a.engine.userProperties.amplitude=0;
  assert.equal(a.hooks.update(a.value).x,640);
  assert.equal(a.value.y,360);
  a.engine.userProperties.speed=0;
  assert.equal(a.hooks.update(a.value).x,640);
});
