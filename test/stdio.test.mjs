import { test } from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { hash } from '../dist/files.js';

test('real stdio handshake, 17 tools, image import/restore, project edits and clean shutdown',async t => {
  const workspace = await fs.mkdtemp(path.join(os.tmpdir(),'we-mcp-stdio-'));
  const configFile = path.join(workspace,'config.json');
  const inbox=path.join(workspace,'inbox'); await fs.mkdir(inbox);
  const png=await sharp({create:{width:32,height:16,channels:4,background:'#66aaff88'}}).png().toBuffer();
  await fs.writeFile(path.join(inbox,'source.png'),png);
  await fs.writeFile(configFile,JSON.stringify({workspace:path.join(workspace,'data'),assetRoots:[inbox]}));
  const transport = new StdioClientTransport({command:process.execPath,args:[fileURLToPath(new URL('../dist/index.js',import.meta.url)),'--config',configFile],stderr:'pipe'});
  const client = new Client({name:'smoke-test',version:'1'});
  t.after(async()=>{await client.close();await fs.rm(workspace,{recursive:true,force:true})});
  await client.connect(transport);
  const tools = await client.listTools(); assert.equal(tools.tools.length,17);
  assert.ok(tools.tools.some(tool=>tool.name==='we_workspace_diagnose'));
  assert.ok(tools.tools.some(tool=>tool.name==='we_preview_move_mouse'));
  const unknownPreview='11111111-1111-4111-8111-111111111111';
  const mouse=await client.callTool({name:'we_preview_move_mouse',arguments:{previewId:unknownPreview,x:0.5,y:0.5}});
  assert.equal(mouse.isError,true); assert.equal(mouse.structuredContent.error.code,'PREVIEW_NOT_FOUND');
  const invalidMouse=await client.callTool({name:'we_preview_move_mouse',arguments:{previewId:unknownPreview,x:1.1,y:0.5}});
  assert.equal(invalidMouse.isError,true);
  const created = await client.callTool({name:'we_project_create',arguments:{name:'test',title:'STDIO Test'}});
  assert.equal(created.isError,undefined);
  const project = created.structuredContent;
  assert.equal(project.validation.valid,true);
  const syntaxError=await client.callTool({name:'we_project_apply',arguments:{projectId:project.projectId,expectedRevision:project.revision,changes:[{path:'wallpaper.js',content:'function ('}]}});
  assert.equal(syntaxError.isError,true); assert.equal(syntaxError.structuredContent.error.code,'VALIDATION_FAILED');
  assert.equal(syntaxError.structuredContent.error.details.javascript.issues[0].code,'JS_SYNTAX');
  const afterSyntaxError=await client.callTool({name:'we_project_inspect',arguments:{projectId:project.projectId}});
  assert.equal(afterSyntaxError.structuredContent.revision,project.revision);
  const syntaxValidation=await client.callTool({name:'we_project_validate',arguments:{projectId:project.projectId}});
  assert.equal(syntaxValidation.structuredContent.javascript.status,'passed');
  assert.equal(syntaxValidation.structuredContent.engineVerification,'unverified');
  // Simulate a legacy/manual broken edit; public apply now refuses to create it.
  const scriptPath=path.join(project.path,'wallpaper.js'),originalScript=await fs.readFile(scriptPath,'utf8');
  await fs.writeFile(scriptPath,'function (');
  const brokenInspect=await client.callTool({name:'we_project_inspect',arguments:{projectId:project.projectId}});
  const brokenValidation=await client.callTool({name:'we_project_validate',arguments:{projectId:project.projectId}});
  assert.equal(brokenValidation.structuredContent.valid,false);
  assert.equal(brokenValidation.structuredContent.javascript.issues[0].code,'JS_SYNTAX');
  for(const name of ['we_preview_open','we_publish_prepare']) {
    const blocked=await client.callTool({name,arguments:{projectId:project.projectId}});
    assert.equal(blocked.isError,true); assert.equal(blocked.structuredContent.error.code,'VALIDATION_FAILED');
  }
  const repaired=await client.callTool({name:'we_project_apply',arguments:{projectId:project.projectId,expectedRevision:brokenInspect.structuredContent.revision,changes:[{path:'wallpaper.js',content:originalScript}]}});
  assert.equal(repaired.isError,undefined); assert.equal(repaired.structuredContent.revision,project.revision);
  const inspectedImage=await client.callTool({name:'we_image_inspect',arguments:{sourceRoot:0,sourcePath:'source.png'}});
  assert.equal(inspectedImage.isError,undefined);
  assert.equal(inspectedImage.content.every(block=>block.type==='text'),true);
  assert.equal(inspectedImage.structuredContent.image.sha256,hash(png));
  const importedImage=await client.callTool({name:'we_image_import',arguments:{projectId:project.projectId,expectedRevision:project.revision,sourceRoot:0,sourcePath:'source.png',expectedSourceHash:hash(png),targetPath:'images/source.png'}});
  assert.equal(importedImage.isError,undefined);
  assert.equal(importedImage.content.every(block=>block.type==='text'),true);
  assert.deepEqual(await fs.readFile(path.join(project.path,'images/source.png')),png);
  const refusedOverwrite=await client.callTool({name:'we_image_import',arguments:{projectId:project.projectId,expectedRevision:importedImage.structuredContent.revision,sourceRoot:0,sourcePath:'source.png',expectedSourceHash:hash(png),targetPath:'images/source.png'}});
  assert.equal(refusedOverwrite.structuredContent.error.code,'IMAGE_EXISTS');
  const restoredImage=await client.callTool({name:'we_project_restore',arguments:{projectId:project.projectId,expectedRevision:importedImage.structuredContent.revision,checkpointId:importedImage.structuredContent.checkpointId}});
  assert.equal(restoredImage.isError,undefined); assert.equal(restoredImage.structuredContent.revision,project.revision);
  await assert.rejects(fs.access(path.join(project.path,'images/source.png')),{code:'ENOENT'});
  assert.deepEqual(await fs.readFile(path.join(inbox,'source.png')),png);
  const scene = await client.callTool({name:'we_project_create',arguments:{name:'scene',title:'Native Scene',templateId:'scene-orbit'}});
  assert.equal(scene.isError,undefined);
  assert.equal(scene.structuredContent.manifest.type,'scene');
  assert.equal(scene.structuredContent.validation.sceneDependencies.every(d=>d.status==='local'),true);
  const changed = await client.callTool({name:'we_project_apply',arguments:{projectId:project.projectId,expectedRevision:project.revision,changes:[{path:'note.txt',content:'hello'}]}});
  assert.ok(changed.structuredContent.checkpointId);
  const conflict = await client.callTool({name:'we_project_apply',arguments:{projectId:project.projectId,expectedRevision:project.revision,changes:[{path:'note.txt',content:'stale'}]}});
  assert.equal(conflict.isError,true); assert.equal(conflict.structuredContent.error.code,'REVISION_CONFLICT');
  const unavailable = await client.callTool({name:'we_preview_open',arguments:{projectId:project.projectId}});
  assert.equal(unavailable.isError,true);
  await client.close();
  await new Promise(r=>setTimeout(r,150));
  await assert.rejects(fs.access(path.join(workspace,'data','server.lock')),{code:'ENOENT'});
});
